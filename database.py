def set_checkpoint(task: str, status: str, details: str = "", db_path: str = DB_PATH) -> None:
    with get_connection(db_path) as conn:
        conn.execute(
            "INSERT OR REPLACE INTO _checkpoints (task, status, updated_at, details) "
            "VALUES (?, ?, datetime('now'), ?)",
            (task, status, details),
        )


def get_checkpoint(task: str, db_path: str = DB_PATH) -> Optional[str]:
    with get_connection(db_path) as conn:
        row = conn.execute(
            "SELECT status FROM _checkpoints WHERE task = ?", (task,)
        ).fetchone()
    return row["status"] if row else None


def is_done(task: str, db_path: str = DB_PATH) -> bool:
    return get_checkpoint(task, db_path) == "done"


def done_tasks(prefix: str, db_path: str = DB_PATH) -> set[str]:
    """All checkpoint names starting with *prefix* whose status is 'done' (one query)."""
    with get_connection(db_path) as conn:
        rows = conn.execute(
            "SELECT task FROM _checkpoints WHERE status = 'done' AND task LIKE ?",
            (prefix + "%",),
        ).fetchall()
    return {r["task"] for r in rows}


def played_seasons(seasons, db_path: str = DB_PATH) -> set[tuple[int, str]]:
    """(player_id, season) pairs found in player_stats_traditional for *seasons*."""
    seasons = list(seasons)
    marks = ", ".join("?" for _ in seasons)
    with get_connection(db_path) as conn:
        rows = conn.execute(
            f"SELECT DISTINCT player_id, season FROM player_stats_traditional WHERE season IN ({marks})",
            seasons,
        ).fetchall()
    return {(r["player_id"], r["season"]) for r in rows}


def table_counts(db_path: str = DB_PATH) -> dict[str, int]:
    """Row count for every user table (for the end-of-run summary)."""
    with get_connection(db_path) as conn:
        names = [r[0] for r in conn.execute(
            "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' "
            "AND name != '_checkpoints' ORDER BY name")]
        return {n: conn.execute(f'SELECT COUNT(*) FROM "{n}"').fetchone()[0] for n in names}
