def _shooting_columns() -> list[str]:
    """Lower-cased column names returned by the two combine shooting endpoints."""
    spots = ["corner_left", "break_left", "top_key", "break_right", "corner_right"]
    stats = ["made", "attempt", "pct"]
    cols = [f"{rng}_{spot}_{st}"                                   # spot-up
            for rng in ("fifteen", "college", "nba") for spot in spots for st in stats]
    cols += [f"off_drib_{rng}_{spot}_{st}"                         # off the dribble
             for rng in ("fifteen", "college")
             for spot in ("break_left", "top_key", "break_right") for st in stats]
    cols += [f"on_move_{rng}_{st}" for rng in ("fifteen", "college") for st in stats]
    return cols


SCHEMA = SCHEMA.replace(
    "{shooting_columns}",
    ",\n    ".join(f"{c} REAL" for c in _shooting_columns()),
)

