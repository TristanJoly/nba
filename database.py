def get_connection(db_path: str = DB_PATH) -> sqlite3.Connection:
    """Return a WAL-mode SQLite connection."""
    conn = sqlite3.connect(db_path, timeout=30)
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA foreign_keys=ON")
    conn.execute("PRAGMA synchronous=NORMAL")
    conn.row_factory = sqlite3.Row
    return conn


def create_tables(db_path: str = DB_PATH) -> None:
    """Create all tables (idempotent)."""
    with get_connection(db_path) as conn:
        # Migrate the old (never-filled) shooting table whose columns did not match the API
        cols = table_columns(conn, "draft_combine_shooting")
        if cols and "fifteen_top_key_made" not in cols:
            if conn.execute("SELECT COUNT(*) FROM draft_combine_shooting").fetchone()[0] == 0:
                conn.execute("DROP TABLE draft_combine_shooting")
        conn.executescript(SCHEMA)
    logger.info("✅ Schema created / verified.")


def table_columns(conn: sqlite3.Connection, table_name: str) -> list[str]:
    return [r[1] for r in conn.execute(f'PRAGMA table_info("{table_name}")').fetchall()]


def upsert_df(
    df: pd.DataFrame,
    table_name: str,
    conn: sqlite3.Connection,
    chunksize: int = 500,
) -> int:
    """
    INSERT OR REPLACE every row of *df* into *table_name*.

    • Lowercases all column names to match the schema.
    • Drops columns that do not exist in the table (the API returns many extras)
      and duplicated columns (the last one wins).
    • NaN → None (so SQLite stores NULL, not the string 'nan').
    • Returns the total number of rows written.
    """
    if df is None or df.empty:
        return 0

    df = df.copy()
    df.columns = [str(c).lower() for c in df.columns]
    df = df.loc[:, ~df.columns.duplicated(keep="last")]

    known = set(table_columns(conn, table_name))
    if not known:
        raise ValueError(f"Table '{table_name}' does not exist – run `--step setup` first.")
    df = df[[c for c in df.columns if c in known]]
    df = df.astype(object)   # numpy scalars → plain Python types sqlite3 understands

    cols = df.columns.tolist()
    col_names   = ", ".join(f'"{c}"' for c in cols)
    placeholders = ", ".join("?" for _ in cols)
    sql = f'INSERT OR REPLACE INTO "{table_name}" ({col_names}) VALUES ({placeholders})'

    rows_written = 0
    for i in range(0, len(df), chunksize):
        chunk = df.iloc[i : i + chunksize]
        # Convert NaN / NaT → None
        data = [
            [None if pd.isna(v) else v for v in row]
            for row in chunk.itertuples(index=False, name=None)
        ]
        conn.executemany(sql, data)
        rows_written += len(chunk)

    conn.commit()
    return rows_written


